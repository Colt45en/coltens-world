//
//   outbox (at-least-once delivery buffer)
//   ├─ event_id (PRIMARY KEY)
//   ├─ destination ['nucleus'|'agenthub'|'audit_log']
//   ├─ status ('pending'|'sent'|'confirmed')
//   ├─ retry_count
//   ├─ next_retry_at
//   └─ 2 indices: status, destination
//
//   idempotency_keys (deduplication; prevents double-execution)
//   ├─ key (PRIMARY KEY; call_id or event_id)
//   ├─ event_id (FK)
//   ├─ result_hash (what was computed)
//   └─ 1 index: event_id
//
//   artifacts (content-addressed storage for replay)
//   ├─ artifact_ref (PRIMARY KEY; content hash)
//   ├─ call_id (FK)
//   ├─ content_hash
//   ├─ created_at
//   └─ 1 index: call_id
//
//   checkpoints (replay verification points)
//   ├─ seq (PRIMARY KEY)
//   ├─ hash (rolling Merkle hash up to seq)
//   ├─ artifact_root (path to artifact storage)
//   ├─ mode ('record'|'replay')
//   ├─ verified (bool)
//   └─ 1 index: verified

