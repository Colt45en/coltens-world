// │  ├─ Register handler for tool requests
// │  └─ Handler demonstrates full approval flow:
// │     1. Check approval_required
// │     2. If yes: emit ApprovalRequested, wait for decision
// │     3. Execute tool
// │     4. Emit ToolResult
// ├─ async waitForApproval(approval_id: string, timeout_ms?: number): Promise<ApprovalDecision | null>
// │  └─ Blocking wait; polls for matching ApprovalDecision event
// ├─ async appendEvent(event: AnyEvent): Promise<void>
// │  └─ POST to /ledger/append
// ├─ generateApprovalId(): string
// │  └─ Create unique approval ID
// ├─ async getCallHistory(call_id: string): Promise<AnyEvent[]>
// │  └─ GET /ledger/call/:call_id
// └─ private polling loop
//    └─ Runs in background; emits 'tool-request' to handler
//
// Event Flow (onToolRequest handler):
// Step 1: Receive ToolExecuteRequest event from ledger
// Step 2: Check payload.approval_required
// Step 3a: If approval needed:
//         - Create approval_id
//         - Emit ApprovalRequested event to ledger
//         - Call waitForApproval (blocking)
//         - If decision != 'approved', return
// Step 3b: If no approval needed:
//         - Skip to Step 4
// Step 4: Execute tool (call tool runtime)
// Step 5: Emit ToolExecuteResult event on ledger
//         - success: boolean
//         - output: any (tool result)
//         - evidence: { execution_time_ms, artifacts }
// Step 6: Nucleus can query result or re-execute
//
// Philosophy: Stateless executor
//   - All state in ledger
//   - Polling is non-blocking (no thread blocking)
//   - Handler can be async (supports tool timeouts)
//   - Idempotent (same event_id → no re-execution)

